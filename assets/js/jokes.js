    var tag = document.getElementById('rndTag');
    var q = document.getElementById('rndQ');
    var a = document.getElementById('rndA');
    if (!tag) return;
    var cur = -1;

    function pick() {
      var n;
      do { n = randInt(0, JOKES.length - 1); } while (n === cur);
      cur = n;
      tag.textContent = LABEL[JOKES[n].c];
      q.textContent = JOKES[n].q;
      a.textContent = '';
    }
